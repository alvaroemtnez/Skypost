#!/usr/bin/env python3
"""Generate ui/theme/Color.kt: the Material 3 colour scheme used when the
phone has no dynamic colour (Android 8-11).

Same algorithm as Material Theme Builder and Android's own dynamic colour:
tonal-spot scheme, 2025 spec, from a single seed colour.

    python3 -m venv /tmp/mcu && /tmp/mcu/bin/pip install materialyoucolor==3.0.4
    /tmp/mcu/bin/python scripts/gen_colors.py > app/src/main/java/io/alvaroedo/skypost/ui/theme/Color.kt
"""

from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors
from materialyoucolor.hct import Hct
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot

SEED = 0x2563C9  # sky blue

# Roles of androidx.compose.material3.ColorScheme (1.4), in its order.
ROLES = """primary onPrimary primaryContainer onPrimaryContainer inversePrimary
secondary onSecondary secondaryContainer onSecondaryContainer
tertiary onTertiary tertiaryContainer onTertiaryContainer
background onBackground surface onSurface surfaceVariant onSurfaceVariant
surfaceTint inverseSurface inverseOnSurface
error onError errorContainer onErrorContainer outline outlineVariant scrim
surfaceBright surfaceDim surfaceContainer surfaceContainerHigh
surfaceContainerHighest surfaceContainerLow surfaceContainerLowest
primaryFixed primaryFixedDim onPrimaryFixed onPrimaryFixedVariant
secondaryFixed secondaryFixedDim onSecondaryFixed onSecondaryFixedVariant
tertiaryFixed tertiaryFixedDim onTertiaryFixed onTertiaryFixedVariant""".split()


def scheme(name: str, builder: str, dark: bool) -> str:
    s = SchemeTonalSpot(Hct.from_int(0xFF000000 | SEED), dark, 0.0, spec_version="2025")
    lines = []
    for role in ROLES:
        argb = getattr(MaterialDynamicColors, role).get_argb(s) & 0xFFFFFFFF
        lines.append(f"    {role} = Color(0x{argb:08X}),")
    return f"internal val {name} = {builder}(\n" + "\n".join(lines) + "\n)\n"


print(f"""// Generated by android/scripts/gen_colors.py from seed #{SEED:06X}. Do not edit.
package io.alvaroedo.skypost.ui.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

{scheme("LightColors", "lightColorScheme", False)}
{scheme("DarkColors", "darkColorScheme", True)}""", end="")
