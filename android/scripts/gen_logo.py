#!/usr/bin/env python3
"""Sky dome logo geometry -> Android vector drawables and repository PNGs.

Decision 0022. Needs shapely and Pillow:

    python3 -m venv /tmp/v && /tmp/v/bin/pip install shapely pillow
    /tmp/v/bin/python android/scripts/gen_logo.py

Writes, all from one shape:
  res/drawable/ic_launcher_foreground.xml   adaptive icon foreground (108 dp grid)
  res/drawable/ic_launcher_monochrome.xml   themed icon (Android 13+)
  res/drawable/ic_splash.xml                splash screen icon, tinted by the theme
  res/drawable/ic_stat_skypost.xml          status-bar icon (24 dp grid)
  docs/icon.png  (512 px square, repository avatar)
  docs/logo.png  (256 px round, README header)

The cut-outs are real geometry (Android vectors have no masks): the dome bubble
minus the station and its two arcs, written with fillType="evenOdd". Never paste
path data by hand; change the shape here and run the script again.
"""
from pathlib import Path

import shapely.affinity as aff
from shapely.geometry import LineString, Point, Polygon, box
from shapely.ops import unary_union

# Default seed. Keep in step with res/values/colors.xml (icon_background) and
# scripts/gen_colors.py. Alternatives (Dusk violet #5A3E96, Ionosphere #1F6F8B,
# Ember #B4532A) are for the planned home-icon setting; see docs/roadmap.md.
SEED = "#26386E"  # Night sky

# Glyph width on the 108 dp adaptive grid. Launchers show at most the 72 dp centre,
# so 40 dp keeps the mark at ~55% of the visible window, like the system's own icons
# (same as MeshConnect).
GLYPH = 40

# Vertical optical correction on the 108 grid, applied after centring on the area
# centroid. Negative moves the mark up. The dome's round top carries little visual
# weight, so even centroid-centred it reads low; see docs/decisions/0022-logo.md.
OPTICAL_DY = -1.0


def arc(cx, cy, r, steps=48):
    """Upper half-circle from left to right (screen y grows downwards)."""
    import math
    return LineString([(cx - r * math.cos(math.pi * i / steps),
                        cy - r * math.sin(math.pi * i / steps)) for i in range(steps + 1)])


def dome():
    """The mark on the 24 dp grid: a speech bubble whose top is the sky, a station inside."""
    cx, cy, r = 12.0, 12.5, 9.0        # dome: half-disc, top at y = 3.5, sides at x = 3 and 21
    bottom, corner = 17.5, 2.0
    half_disc = Point(cx, cy).buffer(r, quad_segs=32).intersection(box(cx - r, cy - r, cx + r, cy))
    body = unary_union([
        box(cx - r, cy, cx + r, bottom - corner),
        box(cx - r + corner, cy, cx + r - corner, bottom),
        Point(cx - r + corner, bottom - corner).buffer(corner, quad_segs=16),
        Point(cx + r - corner, bottom - corner).buffer(corner, quad_segs=16),
    ])
    tail = Polygon([(5.6, 17.0), (5.0, 21.4), (9.6, 17.0)])
    bubble = unary_union([half_disc, body, tail])

    sx, sy, w = 12.0, 13.5, 1.6        # station and its two waves
    cuts = unary_union([
        Point(sx, sy).buffer(1.6, quad_segs=16),
        arc(sx, sy, 3.4).buffer(w / 2, cap_style="round", quad_segs=16),
        arc(sx, sy, 6.0).buffer(w / 2, cap_style="round", quad_segs=16),
    ])
    return bubble.difference(cuts)


def polygons(geom):
    return [geom] if geom.geom_type == "Polygon" else list(geom.geoms)


def path(geom):
    out = []
    for p in polygons(geom):
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            out.append("M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in c) + "Z")
    return "".join(out)


ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"
DOCS = ROOT / "docs"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Sky dome logo, decision 0022. Generated by android/scripts/gen_logo.py (shapely).
     Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}"{attrs}>
    <path
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        android:pathData="{d}"
        tools:ignore="VectorPath" />
</vector>
"""


def write(name, size, d, comment, attrs=""):
    # One outline and three cut-outs (station, inner wave, outer wave).
    if not d.startswith("M") or d.count("Z") != 4:
        raise SystemExit(f"{name}: expected 4 rings, got {d.count('Z')}")
    (RES / f"{name}.xml").write_text(TEMPLATE.format(size=size, d=d, comment=comment, attrs=attrs))
    print(f"{name}.xml  ({len(d)} chars)")


mark = dome()
tray = path(mark)

big = aff.scale(mark, GLYPH / 18, GLYPH / 18, origin=(0, 0))
c = big.centroid
big = aff.translate(big, 54 - c.x, 54 - c.y + OPTICAL_DY)
fg = path(big)

write("ic_launcher_foreground", 108, fg, "Launcher foreground: white sky dome, station cut out to the background.")
write("ic_launcher_monochrome", 108, fg, "Themed-icon (Android 13+) layer: the launcher tints this silhouette.")
write("ic_splash", 108, fg, "Splash screen icon: the launcher mark, tinted for the splash background.",
      attrs='\n    android:tint="@color/splash_glyph"')
# No notification exists yet (radio service, admin alerts: docs/roadmap.md); keep it until then.
write("ic_stat_skypost", 24, tray, "Status-bar icon for every notification. The system uses only its alpha.",
      attrs='\n    tools:ignore="UnusedResources"')


def png(out, size, round_mask):
    """The launcher's visible 72 dp window at `size` px (4x supersampled)."""
    from PIL import Image, ImageDraw
    ss = size * 4
    k = ss / 72.0
    img = Image.new("RGBA", (ss, ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_mask:
        d.ellipse([0, 0, ss - 1, ss - 1], fill=SEED)
    else:
        d.rectangle([0, 0, ss, ss], fill=SEED)
    for p in polygons(aff.translate(big, -18, -18)):
        d.polygon([(x * k, y * k) for x, y in p.exterior.coords], fill="white")
        for ring in p.interiors:
            d.polygon([(x * k, y * k) for x, y in ring.coords], fill=SEED)
    img.resize((size, size), Image.LANCZOS).save(out)
    print(out.relative_to(ROOT))


png(DOCS / "icon.png", 512, round_mask=False)
png(DOCS / "logo.png", 256, round_mask=True)
